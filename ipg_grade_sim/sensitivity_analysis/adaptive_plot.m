set(plot1(2),'DisplayName','RLS','LineWidth',1.25);
set(plot1(3),'DisplayName','Measured','LineWidth',1.25);
set(plot1(4),'DisplayName','True','Color',[0 0 0]);
subtitle('Total Acceleration','interpreter','tex')
% Create xline
xline([0],'--','DisplayName','Braking On/Off')
hold(subplot1,'off');
% Create legend
