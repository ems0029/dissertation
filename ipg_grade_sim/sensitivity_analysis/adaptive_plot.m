    'Position',[0.18918918490193 0.953360216140607 0.666666657752819 0.0428571418637321],...
    'Orientation','horizontal', ...
    'AutoUpdate','off');

xline([subtbl.time(find(diff(subtbl.brake_pressure>0)~=0))],'--','DisplayName','Braking On/Off')


% Create ylabel
